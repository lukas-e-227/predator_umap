def metric_isolation(prey_pos, prey_vel, pred_pos, pred_vel, start_vel):
    mins = prey_pos.min(axis=0)
    maxs = prey_pos.max(axis=0)
    margin = np.maximum(maxs - mins, 1e-6) * 0.1  # as in isolated_agent.ipynb
    return measure_isolation(prey_pos, (mins - margin, maxs + margin))


