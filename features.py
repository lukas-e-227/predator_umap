# put trajectories in the prey group's frame: COM at the origin, group heading along +x.
# the prey swim in the y=0 plane, so the rotation is about y and the predator's y stays its
# height above that plane.

def heading_angle(heading):
    return np.arctan2(heading[2], heading[0])


def rotate_to_forward(points, angle):
    x = np.cos(angle) * points[..., 0] + np.sin(angle) * points[..., 2]
    z = -np.sin(angle) * points[..., 0] + np.cos(angle) * points[..., 2]
    return np.stack([x, points[..., 1], z], axis=-1)


def align_trajectory(trajectory, com, group_heading, frame='initial', mirror=False):
    trajectory = np.asarray(trajectory, dtype=float)
    com = np.asarray(com, dtype=float)
    group_heading = np.asarray(group_heading, dtype=float)

    if frame == 'initial':  # one frame for the whole attack, fixed at the first iteration
        aligned = rotate_to_forward(trajectory - com[0], heading_angle(group_heading[0]))
    elif frame == 'moving':  # the group's own frame at every iteration
        aligned = np.stack([
            rotate_to_forward(pos - c, heading_angle(h))
            for pos, c, h in zip(trajectory, com, group_heading)
        ])
    else:
        raise ValueError("frame must be 'initial' or 'moving'")

    if mirror:  # treat left/right mirrored attacks as the same strategy
        widest = aligned[np.argmax(np.abs(aligned[:, 2])), 2]
        if widest < 0:
            aligned[:, 2] *= -1
    return aligned


def align_trajectories(data, frame='initial', mirror=False):
    return {
        i: align_trajectory(data['trajectory'][i]['values'], data['com'][i]['values'],
                            data['group_heading'][i]['values'], frame=frame, mirror=mirror)
        for i in data['trajectory']
    }


