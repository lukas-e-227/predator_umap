def extract_data_from_folder(folder_path, metrics=None, attack_dir=None,
                             file_prefix="simulation_positions", start_idx=42):
    if metrics is None:
        metrics = list(METRICS)
    unknown = [key for key in metrics if key not in METRICS]
    if unknown:
        raise KeyError(f"unknown metrics {unknown}, available: {list(METRICS)}")

    file_pattern = os.path.join(folder_path, f"{file_prefix}*")
    file_list = glob.glob(file_pattern)
    print(file_list)
    data_dict = {key: {} for key in metrics}
    attributes = {}
    for i, file_path in enumerate(file_list):
        with h5py.File(file_path, 'r') as f:
            if i == 0:
                attributes = {
                    key: f.attrs[key]
                    for key in f.attrs
                }
            file_attack_dir = read_attack_dir(f)
            if attack_dir is not None and attack_dir != file_attack_dir:
                continue

            iterations = sorted(
                [key for key in f.keys() if key.startswith('iteration_')],
                key=lambda x: int(x.split('_')[1])
            )

            values = {key: [] for key in metrics}
            start_vel = None
            for idx, iter in enumerate(iterations):
                if idx < start_idx: continue
                group = f[iter]
                positions = group['positions'][:]
                velocities = group['velocities'][:]
                prey_pos = positions[:-1]
                prey_vel = velocities[:-1]
                pred_pos = positions[-1]
                pred_vel = velocities[-1]
                if start_vel is None:
                    start_vel = pred_vel

                for key in metrics:
                    values[key].append(METRICS[key](prey_pos, prey_vel, pred_pos, pred_vel, start_vel))

            for key in metrics:
                if values[key]:
                    # file and start_idx let umap_explorer find this run's raw log again
                    data_dict[key][i] = {'values': values[key], 'attack_dir': file_attack_dir,
                                         'file': file_path, 'start_idx': start_idx}

    return data_dict

