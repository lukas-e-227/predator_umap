def normalize(v):
    return v / np.linalg.norm(v)


def get_avg_pred_dist(positions):
    prey_pos = positions[:-1]
    pred_pos = positions[-1]
    distances = np.linalg.norm(prey_pos - pred_pos, axis=1)

    return np.mean(distances)


def get_nnds(positions):
    diff = positions[:, np.newaxis, :] - positions[np.newaxis, :, :]
    dist_matrix = np.linalg.norm(diff, axis=2)
    np.fill_diagonal(dist_matrix, np.inf)
    min_dists = np.min(dist_matrix, axis=1)

    return min_dists


def relative_heading_angle(start_vel, current_vel, degrees=True):
    start_vel = np.asarray(start_vel, dtype=float)
    current_vel = np.asarray(current_vel, dtype=float)

    heading_start = np.arctan2(start_vel[..., 2], start_vel[..., 0])
    heading_curr  = np.arctan2(current_vel[..., 2], current_vel[..., 0])

    angle = heading_curr - heading_start
    # wrap to (-pi, pi]
    angle = (angle + np.pi) % (2 * np.pi) - np.pi

    return np.degrees(angle) if degrees else angle


def dot_aim_at_com(pred_pos, pred_vel, com):
    to_com = normalize(com - pred_pos)
    return np.dot(to_com, normalize(pred_vel))


def dot_aim_at_closest(pred_pos, pred_vel, closest):
    to_closest = normalize(closest - pred_pos)
    return np.dot(to_closest, normalize(pred_vel))


def mirror_points(points, mins, maxs):
    d = points.shape[1]
    mirrored = [points]
    for axis in range(d):
        lo = points.copy(); lo[:, axis] = 2 * mins[axis] - points[:, axis]
        hi = points.copy(); hi[:, axis] = 2 * maxs[axis] - points[:, axis]
        mirrored.append(lo); mirrored.append(hi)
    return np.vstack(mirrored)


def bounded_voronoi_volumes(points, bbox):
    points = np.asarray(points, dtype=float)
    n = len(points)
    ptp = np.ptp(points, axis=0)
    non_zero_dims = np.where(ptp > 0)[0]

    is_2d = np.any(np.ptp(points, axis=0) == 0)

    pts = points[:, non_zero_dims]
    mins = np.asarray(bbox[0])[non_zero_dims]
    maxs = np.asarray(bbox[1])[non_zero_dims]

    assert np.all(pts >= mins) and np.all(pts <= maxs), \
        "bbox must fully contain all points at all timesteps"

    all_points = mirror_points(pts, mins, maxs)
    vor = Voronoi(all_points)

    volumes = np.full(n, np.nan)
    for i in range(n):  # only the first n rows of vor.point_region are real points
        region = vor.regions[vor.point_region[i]]
        if -1 in region or len(region) == 0:
            continue  # shouldn't happen once mirrors are added; bbox may be too tight
        vertices = vor.vertices[region]
        if is_2d:
            x, y = vertices[:, 0], vertices[:, 1]
            volumes[i] = 0.5 * np.abs(np.dot(x, np.roll(y, 1)) - np.dot(y, np.roll(x, 1)))
        else:
            try:
                volumes[i] = ConvexHull(vertices).volume
            except Exception:
                volumes[i] = np.nan  # degenerate (near-coplanar) hull
    return volumes


def measure_isolation(points, bbox):
    volumes = bounded_voronoi_volumes(points, bbox)
    max_volume = np.nanmax(volumes)
    mean_volume = np.nanmean(volumes)
    return 1.0 - (mean_volume / max_volume)


def metric_aim_com(prey_pos, prey_vel, pred_pos, pred_vel, start_vel):
    return dot_aim_at_com(pred_pos, pred_vel, np.mean(prey_pos, axis=0))


def metric_aim_closest(prey_pos, prey_vel, pred_pos, pred_vel, start_vel):
    dists_to_pred = np.linalg.norm(prey_pos - pred_pos, axis=1)
    return dot_aim_at_closest(pred_pos, pred_vel, prey_pos[np.argmin(dists_to_pred)])


def metric_dist_com(prey_pos, prey_vel, pred_pos, pred_vel, start_vel):
    return np.linalg.norm(pred_pos - np.mean(prey_pos, axis=0))


