# UMAP axes carry no units, so a lobe of the embedding means nothing until you can say
# what the points sitting in it were doing. coloring the *same* embedding by each
# metric turns the picture into a legend - "this lobe is fast and far from the COM" -
# and that is the only way a region of a UMAP plot can be given a reading.

def row_metric_values(res, data, key, align=True, frame='initial', mirror=False):
    """-> (n_rows, d) raw values of `key`, one row per point of res['embedding']

    Takes either result dict: a per-iteration row gets the value at its iteration, a
    per-segment row the mean over that segment. The values are raw - not z-scored, not
    block-balanced - so a color axis is in the metric's own units.

    align/frame/mirror should match the call that produced `res`, otherwise the
    trajectory is being read in a different frame from the one it was embedded in.
    """
    if key not in data:
        raise KeyError(f"{key} not in data, available: {list(data)}")
    ids = np.asarray(res['ids'])
    runs = {}
    for i in sorted(set(ids.tolist())):
        arr = np.asarray(metric_series(data, key, i, align, frame, mirror), dtype=float)
        runs[i] = arr.reshape(arr.shape[0], -1)

    if 'iterations' in res:  # iteration_umap: the value at that very iteration
        return np.stack([runs[i][t] for i, t in zip(ids, res['iterations'])])
    if 'segments' in res:  # segment_umap: the mean over the segment's share of the run
        n_segments = int(np.max(res['segments'])) + 1
        values = []
        for i, s in zip(ids, res['segments']):
            arr = runs[i]
            edges = np.linspace(0, len(arr), n_segments + 1).astype(int)
            values.append(arr[edges[s]:max(edges[s + 1], edges[s] + 1)].mean(axis=0))
        return np.stack(values)
    raise KeyError("res must come from iteration_umap or segment_umap")


def metric_columns(res, data, color_metrics=None, align=True, frame='initial', mirror=False,
                   include_features=True):
    """-> {label: (n_rows,)}, one column per scalar metric, vectors split by component

    color_metrics=None takes every scalar metric in `data` - the vector ones
    (trajectory, com, group_heading) are left out unless asked for by name, since a
    position is mostly a restatement of the clock.

    A controller_umap result also carries its own feature columns, such as thrust and
    closing_speed, which are not metrics in `data` at all. Those come first and can be
    switched off with include_features=False.
    """
    if color_metrics is None:
        color_metrics = [key for key, series in data.items()
                         if np.asarray(next(iter(series.values()))['values'][0]).size == 1]
    columns = dict(res['features']) if include_features and 'features' in res else {}
    for key in color_metrics:
        values = row_metric_values(res, data, key, align=align, frame=frame, mirror=mirror)
        if values.shape[1] == 1:
            columns[key] = values[:, 0]
        else:
            names = ('x', 'y', 'z') if values.shape[1] == 3 else range(values.shape[1])
            for c, name in enumerate(names):
                columns[f"{key}[{name}]"] = values[:, c]
    return columns


def metric_map(res, data, color_metrics=None, cmap='viridis', robust=True, s=10, ncols=4,
               align=True, frame='initial', mirror=False, include_features=True,
               filename=None):
    """-> {'panels': {label: values}, 'spearman': {label: rho}, 'fig'}

    The embedding from `res`, repeated once per metric. The first panel is progress, so
    every other panel can be compared against the clock directly. A controller_umap
    result adds pass_time as the second panel and its own feature columns after it.

    robust=True clips the color scale to the 2nd-98th percentile; one outlier
    iteration otherwise flattens a whole panel to a single color.
    """
    from scipy.stats import spearmanr

    embedding = res['embedding']
    panels = {'progress': np.asarray(res['progress'], dtype=float)}
    if 'pass_time' in res:
        panels['pass_time'] = np.asarray(res['pass_time'], dtype=float)
    panels.update(metric_columns(res, data, color_metrics, align=align, frame=frame,
                                 mirror=mirror, include_features=include_features))

    nrows = int(np.ceil(len(panels) / ncols))
    fig, axes = plt.subplots(nrows, ncols, figsize=(4.8 * ncols, 4.4 * (nrows + 0.5)), squeeze=False)
    for ax, (label, values) in zip(axes.ravel(), panels.items()):
        lo, hi = (np.nanpercentile(values, [2, 98]) if robust
                  else (np.nanmin(values), np.nanmax(values)))
        points = ax.scatter(embedding[:, 0], embedding[:, 1], c=values, cmap=cmap,
                            vmin=lo, vmax=hi if hi > lo else lo + 1e-9, s=s, alpha=0.85,
                            linewidth=0)
        fig.colorbar(points, ax=ax, fraction=0.045, pad=0.02)
        ax.set_title(label, fontsize=13)
        ax.set_xticks([]); ax.set_yticks([])
        for side in ('top', 'right'):
            ax.spines[side].set_visible(False)
    for ax in axes.ravel()[len(panels):]:
        ax.set_visible(False)

    fig.suptitle(f"what the embedding means  |  {len(panels)} panels over "
                 f"{len(embedding)} points", fontsize=16)
    fig.tight_layout()
    if filename:
        os.makedirs("./new_images", exist_ok=True)
        fig.savefig(f"./new_images/metric_map_{filename}.pdf", format='pdf')

    # a metric that tracks progress this closely is a clock, not a behaviour: it will
    # make any embedding look like a time gradient whatever else is in the features
    rho = {label: (float(spearmanr(values, panels['progress']).statistic)
                   if np.std(values) > 0 else float('nan'))  # a constant metric has none
           for label, values in panels.items() if label != 'progress'}
    print("rank correlation with progress (|rho| > 0.8 means the metric is mostly time):")
    for label, value in sorted(rho.items(), key=lambda kv: -abs(np.nan_to_num(kv[1]))):
        print(f"  {label:<22} {'constant' if np.isnan(value) else f'{value:+.2f}'}")

    return {'panels': panels, 'spearman': rho, 'fig': fig}

# ---------------------------------------------------------------------------
# 6. behavioural states: what happens at which point of the attack
# ---------------------------------------------------------------------------
# cluster the points *in feature space* into a handful of states, then stop looking at
# the embedding and look at when each state is occupied. this is the readout the UMAP
# itself cannot give: "state 2 holds until 40%, state 0 takes over, state 4 only ever
# happens in three runs". the state profile says what each state is in metric terms,
# so a state can be named, and the transition matrix says what usually follows what.

def behavioural_states(res, data, n_states=6, method='kmeans', color_metrics=None,
                       n_bins=20, n_grid=200, min_cluster_size=50, align=True,
                       frame='initial', mirror=False, include_features=True,
                       random_state=42, filename=None):
    """-> {'labels', 'occupancy', 'profiles', 'transitions', 'summary', 'fig'}

    Takes a segment_umap or iteration_umap result and clusters res['X'] - the feature
    space, never the embedding, since UMAP distances are not metric.

    method='kmeans' gives exactly n_states and assigns every point, which is what the
    occupancy curves want; method='hdbscan' finds its own number and leaves outliers
    unassigned (shown as 'unclustered', and excluded from the profiles).

    Reads, in the order of the panels:
      - where the states sit in the embedding (so this is comparable with metric_map)
      - occupancy: share of points in each state against progress, over all runs
      - ethogram: one strip per run, so you see whether that share is every run doing
        the same thing or a few runs doing something else
      - profiles: mean z-scored metric value per state - this is what names a state
      - transitions: P(next state | current state), self-transitions removed
    """
    from sklearn.cluster import KMeans
    from matplotlib.colors import ListedColormap
    from matplotlib.patches import Patch

    X = res['X']
    progress = np.asarray(res['progress'], dtype=float)
    ids = np.asarray(res['ids'])
    attack_dirs = np.asarray(res['attack_dirs'])

    if method == 'kmeans':
        n_states = min(n_states, len(X))
        labels = KMeans(n_clusters=n_states, n_init=10,
                        random_state=random_state).fit_predict(X)
    elif method == 'hdbscan':
        labels = HDBSCAN(min_cluster_size=min_cluster_size).fit_predict(X)
    else:
        raise ValueError("method must be 'kmeans' or 'hdbscan'")
    states = sorted(set(labels.tolist()) - {-1})
    if not states:
        raise ValueError("no clusters found; lower min_cluster_size or use method='kmeans'")

    palette = [plt.cm.tab10.colors[k % 10] for k in range(len(states))]
    state_color = dict(zip(states, palette))
    index = {state: k for k, state in enumerate(states)}  # state -> row/column position

    # ---- occupancy: share of each state inside a progress bin ----
    edges = np.linspace(0.0, 1.0, n_bins + 1)
    centres = (edges[:-1] + edges[1:]) / 2
    binned = np.clip(np.digitize(progress, edges) - 1, 0, n_bins - 1)
    occupancy = np.zeros((len(states) + 1, n_bins))  # last row = unclustered
    for b in range(n_bins):
        sel = binned == b
        total = max(int(sel.sum()), 1)
        for state in states:
            occupancy[index[state], b] = np.sum(labels[sel] == state) / total
        occupancy[-1, b] = np.sum(labels[sel] == -1) / total

    # ---- ethogram: every run resampled onto the same progress grid ----
    run_ids = sorted(set(ids.tolist()), key=lambda i: (str(attack_dirs[ids == i][0]), i))
    grid = np.linspace(0.0, 1.0, n_grid)
    strips = np.full((len(run_ids), n_grid), len(states), dtype=float)  # default = noise
    for row, i in enumerate(run_ids):
        where = np.flatnonzero(ids == i)
        nearest = np.abs(grid[:, None] - progress[where][None, :]).argmin(axis=1)
        strips[row] = [index.get(labels[where[k]], len(states)) for k in nearest]

    # ---- profiles: what is a state, in metric terms ----
    columns = metric_columns(res, data, color_metrics, align=align, frame=frame,
                             mirror=mirror, include_features=include_features)
    names = list(columns)
    raw = np.column_stack([columns[name] for name in names]) if names else np.zeros((len(X), 0))
    std = raw.std(axis=0)
    zscored = (raw - raw.mean(axis=0)) / np.where(std > 0, std, 1.0)
    profiles = pd.DataFrame(
        [zscored[labels == state].mean(axis=0) for state in states],
        index=[f"state {state}" for state in states], columns=names)

    # ---- transitions: what follows what, within a run, self-transitions dropped ----
    counts = np.zeros((len(states), len(states)))
    dwell = {state: [] for state in states}
    for i in run_ids:
        sequence = labels[ids == i]  # rows are kept in time order within a run
        run_length = 1
        for a, b in zip(sequence[:-1], sequence[1:]):
            if a == b:
                run_length += 1
                continue
            if a in index:
                dwell[a].append(run_length)
            run_length = 1
            if a in index and b in index:
                counts[index[a], index[b]] += 1
        if sequence[-1] in index:
            dwell[sequence[-1]].append(run_length)
    totals = counts.sum(axis=1, keepdims=True)
    transitions = pd.DataFrame(counts / np.where(totals > 0, totals, 1.0),
                               index=[f"from {s}" for s in states],
                               columns=[f"to {s}" for s in states])

    # ---- figure ----
    fig = plt.figure(figsize=(21, 12))
    gs = fig.add_gridspec(2, 3, height_ratios=[1.0, 0.95], hspace=0.3, wspace=0.25)

    ax = fig.add_subplot(gs[0, 0])
    noise = labels == -1
    if noise.any():
        ax.scatter(res['embedding'][noise, 0], res['embedding'][noise, 1], s=8,
                   color='0.8', linewidth=0, label='unclustered')
    for state in states:
        sel = labels == state
        ax.scatter(res['embedding'][sel, 0], res['embedding'][sel, 1], s=10, alpha=0.8,
                   linewidth=0, color=state_color[state], label=f"state {state}")
    ax.set_title('states in the embedding', fontsize=13)
    ax.set_xlabel('UMAP 1', fontsize=12); ax.set_ylabel('UMAP 2', fontsize=12)
    ax.set_xticks([]); ax.set_yticks([])
    ax.legend(fontsize=10, markerscale=2.5, loc='best')

    ax = fig.add_subplot(gs[0, 1])
    bands, band_colors, band_labels = occupancy[:len(states)], list(palette), \
        [f"state {s}" for s in states]
    if occupancy[-1].any():  # unclustered points stack on top, in grey
        bands = occupancy
        band_colors = band_colors + ['0.8']
        band_labels = band_labels + ['unclustered']
    ax.stackplot(centres, bands, colors=band_colors, labels=band_labels)
    ax.set_xlim(0, 1); ax.set_ylim(0, 1)
    ax.set_xlabel('progress through attack', fontsize=12)
    ax.set_ylabel('share of points', fontsize=12)
    ax.set_title('state occupancy over the attack', fontsize=13)
    ax.legend(fontsize=9, loc='center right', framealpha=0.85)  # inside, the ethogram is next

    ax = fig.add_subplot(gs[0, 2])
    ax.imshow(strips, aspect='auto', interpolation='nearest', extent=(0, 1, len(run_ids), 0),
              cmap=ListedColormap(palette + [(0.8, 0.8, 0.8)]),
              vmin=-0.5, vmax=len(states) + 0.5)
    for row, i in enumerate(run_ids):  # a direction tag down the left edge
        direction = str(attack_dirs[ids == i][0])
        ax.barh(row + 0.5, 0.03, left=-0.04, height=1.0,
                color=ATTACK_DIR_COLORS.get(direction, '0.5'))
    ax.set_xlim(-0.04, 1)
    ax.set_xlabel('progress through attack', fontsize=12)
    ax.set_ylabel('run', fontsize=12)
    ax.set_yticks([])
    ax.set_title('ethogram: one strip per run', fontsize=13)
    present = list(dict.fromkeys(str(attack_dirs[ids == i][0]) for i in run_ids))
    ax.legend(handles=[Patch(color=ATTACK_DIR_COLORS.get(d, '0.5'), label=d) for d in present],
              fontsize=9, loc='center left', bbox_to_anchor=(1.01, 0.5))

    ax = fig.add_subplot(gs[1, :2])
    if names:
        limit = np.abs(profiles.values).max() or 1.0
        image = ax.imshow(profiles.values, cmap='RdBu_r', vmin=-limit, vmax=limit,
                          aspect='auto')
        ax.set_xticks(range(len(names)))
        ax.set_xticklabels(names, rotation=25, ha='right', fontsize=11)
        ax.set_yticks(range(len(states)))
        ax.set_yticklabels(profiles.index, fontsize=11)
        for r in range(len(states)):
            for c in range(len(names)):
                value = profiles.values[r, c]
                ax.text(c, r, f"{value:+.1f}", ha='center', va='center', fontsize=9,
                        color='white' if abs(value) > 0.6 * limit else 'black')
        fig.colorbar(image, ax=ax, fraction=0.025, pad=0.01,
                     label='mean z-score across all points')
        ax.set_title('state profiles: what each state is, in metric terms', fontsize=13)
    else:
        ax.set_visible(False)

    ax = fig.add_subplot(gs[1, 2])
    image = ax.imshow(transitions.values, cmap='Blues', vmin=0, vmax=1)
    ax.set_xticks(range(len(states))); ax.set_xticklabels(states, fontsize=11)
    ax.set_yticks(range(len(states))); ax.set_yticklabels(states, fontsize=11)
    ax.set_xlabel('to state', fontsize=12); ax.set_ylabel('from state', fontsize=12)
    for r in range(len(states)):
        for c in range(len(states)):
            value = transitions.values[r, c]
            if value > 0.01:
                ax.text(c, r, f"{value:.2f}", ha='center', va='center', fontsize=9,
                        color='white' if value > 0.6 else 'black')
    fig.colorbar(image, ax=ax, fraction=0.045, pad=0.02, label='P(next | current)')
    ax.set_title('transitions (self-transitions dropped)', fontsize=13)

    fig.suptitle(f"behavioural states  |  {method}, {len(states)} states, "
                 f"{len(run_ids)} runs, {len(X)} points", fontsize=16)
    if filename:
        os.makedirs("./new_images", exist_ok=True)
        fig.savefig(f"./new_images/states_{filename}.pdf", format='pdf', bbox_inches='tight')

    # ---- the readout in words ----
    summary = pd.DataFrame({
        'share': [float(np.mean(labels == state)) for state in states],
        'peak_at': [float(centres[int(np.argmax(occupancy[index[state]]))]) for state in states],
        'runs': [int(len(set(ids[labels == state].tolist()))) for state in states],
        'mean_dwell': [float(np.mean(dwell[state])) if dwell[state] else np.nan
                       for state in states],
        'top_metric': [profiles.loc[f"state {state}"].abs().idxmax() if names else ''
                       for state in states],
    }, index=[f"state {state}" for state in states])
    print(f"{len(run_ids)} runs, {len(X)} points, {len(states)} states"
          + (f", {int(np.sum(labels == -1))} unclustered" if (labels == -1).any() else ""))
    for state in states:
        row = summary.loc[f"state {state}"]
        print(f"  state {state}: {row['share']:.0%} of points, peaks at {row['peak_at']:.0%} "
              f"through the attack, seen in {int(row['runs'])}/{len(run_ids)} runs, "
              f"dwell {row['mean_dwell']:.0f} samples, driven by {row['top_metric']}")
    if len(states) > 1:
        order = np.argsort([summary.loc[f'state {s}', 'peak_at'] for s in states])
        print("  states in the order they peak: "
              + " -> ".join(f"state {states[k]}" for k in order))

    return {'labels': labels, 'states': states, 'occupancy': occupancy, 'bins': centres,
            'profiles': profiles, 'transitions': transitions, 'summary': summary,
            'ethogram': strips, 'run_ids': run_ids, 'fig': fig}
