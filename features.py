def body_frames(velocities, up_world=(0.0, 1.0, 0.0)):
    """-> (n, 3, 3) one orthonormal frame per iteration, rows forward / right / up

    forward is the predator's heading. right is perpendicular to both the heading and
    the world up axis, and up completes the frame. The construction degenerates when
    the predator flies along the world up axis, in which case any perpendicular will
    do and one is picked arbitrarily.
    """
    velocities = np.asarray(velocities, dtype=float)
    up_world = np.asarray(up_world, dtype=float)

    speed = np.linalg.norm(velocities, axis=1, keepdims=True)
    forward = np.divide(velocities, speed, out=np.zeros_like(velocities), where=speed > 0)
    forward[speed[:, 0] == 0] = [1.0, 0.0, 0.0]  # standing still: keep the frame defined

    right = np.cross(forward, up_world)
    degenerate = np.linalg.norm(right, axis=1) < 1e-8
    if degenerate.any():  # heading parallel to the world up axis
        fallback = np.cross(forward[degenerate], [1.0, 0.0, 0.0])
        still_bad = np.linalg.norm(fallback, axis=1) < 1e-8
        fallback[still_bad] = np.cross(forward[degenerate][still_bad], [0.0, 0.0, 1.0])
        right[degenerate] = fallback
    right /= np.linalg.norm(right, axis=1, keepdims=True)

    return np.stack([forward, right, np.cross(right, forward)], axis=1)


def to_body(frames, vectors):
    """-> (n, 3) world-frame vectors expressed in the per-iteration body frame"""
    return np.einsum('nij,nj->ni', frames, np.asarray(vectors, dtype=float))


def predator_acceleration(velocities, dt=0.02, drag=0.95, output_step=0.1):
    """-> (n, 3) mean acceleration commanded over each logged step

    The log keeps one frame every output_step seconds while the simulation runs at dt,
    so the controller ran n_sub = output_step / dt times in between. Inverting
    v <- (v + a dt) * drag over n_sub steps, with a held constant, gives

        a = (v_next - drag^n_sub v) / (dt * sum_i drag^i),  i = 1 .. n_sub

    The estimate is biased wherever the speed clamp was active, and the last frame has
    no successor, so it repeats the one before it. Against the real network output this
    recovers the commanded direction with a mean cosine of about 0.82.
    """
    velocities = np.asarray(velocities, dtype=float)
    n_sub = max(int(round(output_step / dt)), 1)
    decay = drag ** n_sub
    gain = dt * sum(drag ** i for i in range(1, n_sub + 1))
    acceleration = (velocities[1:] - decay * velocities[:-1]) / gain
    return np.vstack([acceleration, acceleration[-1:]])


def pass_times(dist_closest, output_step=0.1, prominence=0.5):
    """-> (n,) seconds relative to the closest approach each iteration belongs to

    A pass is one approach and miss: a local minimum of the distance to the nearest
    prey, after which the distance grows again. Each iteration is assigned to the pass
    whose minimum is nearest in time. The value is negative while closing in, zero at
    the closest approach and positive while pulling away.

    prominence is in length units and filters out noise wiggles. find_peaks ignores the
    ends of the series, so the global minimum is always added: in your runs it is the
    kill, which ends the simulation.
    """
    from scipy.signal import find_peaks

    dist_closest = np.asarray(dist_closest, dtype=float)
    troughs, _ = find_peaks(-dist_closest, prominence=prominence)
    troughs = np.unique(np.append(troughs, int(np.argmin(dist_closest))))
    index = np.arange(len(dist_closest))
    nearest = troughs[np.abs(index[:, None] - troughs[None, :]).argmin(axis=1)]
    return (index - nearest) * output_step, troughs


def window_reduce(array, window, window_stat='mean'):
    """-> (n, d) with window_stat='mean', (n, d * window) with 'stack'

    One row per iteration still, but each row now describes the `window` iterations
    centred on it rather than that one instant. The window slides and never shrinks:
    near either end of a run it is clamped to the first or last full window, so every
    row summarises the same amount of time.

    'mean' averages the window, leaving the column count alone. A direction vector
    averages to less than unit length when the bearing swung during the window, so its
    length becomes a measure of how much the direction turned. The mean of a gradient
    telescopes into the finite difference across the window, so prey_dir_rate and
    closing_speed become rates measured over the window rather than over one step.

    'stack' lays the window's samples side by side instead, in time order, so a row
    keeps the shape of the manoeuvre and not just its average. This is the same knob
    as the superseded iteration_features in metrics.ipynb, and it multiplies the
    column count by `window`.
    """
    array = np.asarray(array, dtype=float)
    n = len(array)
    if window < 1:
        raise ValueError("window must be >= 1")
    if window > n:
        raise ValueError(f"window={window} is longer than the run ({n} iterations)")
    if window == 1 and window_stat == 'mean':
        return array
    starts = np.clip(np.arange(n) - window // 2, 0, n - window)
    view = np.stack([array[s:s + window] for s in starts])  # (n, window, d)
    if window_stat == 'mean':
        return view.mean(axis=1)
    if window_stat == 'stack':
        return view.reshape(n, -1)
    raise ValueError("window_stat must be 'mean' or 'stack'")


def window_note(window, window_stat='mean', output_step=0.1):
    """-> a plot-title fragment naming the window in iterations and in seconds"""
    if window == 1:
        return ", one iteration per point"
    return (f", {window_stat} over {window} iterations "
            f"({window * output_step:.1f} s) per point")


def window_labels(labels, window, window_stat='mean'):
    """-> one label per column of a stacked block, as 'thrust@-2' ... 'thrust@+2'

    The offsets are iterations relative to the centre of the window, so the sign says
    whether the column is the recent past or the near future of the row's own instant.
    """
    if window_stat != 'stack' or window == 1:
        return list(labels)
    offsets = np.arange(window) - window // 2
    return [f"{label}@{offset:+d}" for offset in offsets for label in labels]


