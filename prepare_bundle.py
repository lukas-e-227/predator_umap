"""Build the inputs of build_static.py. Run it locally, once.

    python prepare_bundle.py

It needs the notebook's Python environment (umap-learn and the rest), and it reads
the hdf5 logs from data/. It writes two files:

- features.py: the notebook's feature code, cells 1 to 6 of controller_umap.ipynb,
  so the export builds the saved views' point sets the same way the notebook does.
- bundle.pkl: the extracted data (ctrl) and the embedding (res), computed exactly as
  the notebook's cells do it, so the saved views match their points.

Run it again whenever the notebook's feature code or the data changes.
"""
import json
import os
import pickle
import sys
import time
import types

import matplotlib
matplotlib.use('Agg')

HERE = os.path.dirname(os.path.abspath(__file__))
NOTEBOOK = os.path.join(HERE, '..', 'evo_analysis', 'controller_umap.ipynb')
DATA = os.path.join(HERE, 'data')
FEATURE_CELLS = 6        # the cells that only define functions and constants


def write_features():
    nb = json.load(open(NOTEBOOK, encoding='utf-8'))
    cells = [''.join(c['source']) for c in nb['cells'] if c['cell_type'] == 'code']
    body = '\n\n'.join(cells[:FEATURE_CELLS])
    head = ('"""The feature code of controller_umap.ipynb, cells 1 to %d.\n\n'
            'Generated by prepare_space.py; edit the notebook, not this file.\n"""\n'
            'import matplotlib\nmatplotlib.use("Agg")\n\n' % FEATURE_CELLS)
    with open(os.path.join(HERE, 'features.py'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(head + body + '\n')


def main():
    write_features()
    sys.path.insert(0, HERE)
    import features

    t0 = time.time()
    # the same calls as the notebook's cells 7 and 8
    ctrl = features.extract_data_from_folder(DATA, metrics=features.CONTROLLER_SCHOOL_METRICS)
    res = features.controller_school_umap(ctrl)
    print(f"features and UMAP in {time.time() - t0:.0f} s, {len(res['ids'])} points")

    # run files by name only: the export finds them in its own data folder
    for series in ctrl.values():
        for entry in series.values():
            entry['file'] = os.path.basename(entry['file'].replace('\\', '/'))

    # the fitted reducer is large and only its settings are read
    reducer = res.get('reducer')
    keep = {k: v for k, v in res.items() if k != 'reducer'}
    keep['reducer'] = types.SimpleNamespace(**{
        k: getattr(reducer, k) for k in ('n_neighbors', 'min_dist', 'metric', 'random_state')
        if hasattr(reducer, k)})
    for k, v in list(keep.items()):
        if type(v).__module__.startswith('matplotlib'):
            del keep[k]
    with open(os.path.join(HERE, 'bundle.pkl'), 'wb') as f:
        pickle.dump({'ctrl': ctrl, 'res': keep}, f, protocol=pickle.HIGHEST_PROTOCOL)
    print('wrote bundle.pkl,', round(os.path.getsize(os.path.join(HERE, 'bundle.pkl')) / 1e6, 1), 'MB')


if __name__ == '__main__':
    main()
